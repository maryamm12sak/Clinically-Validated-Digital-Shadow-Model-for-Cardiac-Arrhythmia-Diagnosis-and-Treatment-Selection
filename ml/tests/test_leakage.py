"""Cheap leakage checks: model inputs must come from the waveform only, never from PTB-XL metadata."""
import re
from pathlib import Path

import pandas as pd
import pytest

from benchmark import feature_matrix
from src import feature_extraction
from src.feature_extraction import all_columns, feature_names

# ptbxl_database.csv metadata and annotation columns that must never be model inputs
FORBIDDEN = ["extra_beats", "pacemaker", "heart_axis", "report", "scp_codes", "infarction_stadium1",
             "infarction_stadium2", "baseline_drift", "static_noise", "burst_noise",
             "electrodes_problems", "validated_by", "validated_by_human", "second_opinion",
             "initial_autogenerated_report", "nurse", "site", "device", "recording_date",
             "strat_fold", "patient_id", "ecg_id", "filename_lr", "filename_hr"]
ALLOWED_PREFIXES = ("rr_", "int_", "amp_", "psd_", "dwt_")


def test_feature_names_are_waveform_features_only(dataset):
    names = feature_names()
    assert all(n.startswith(ALLOWED_PREFIXES) for n in names)
    assert not set(names) & set(FORBIDDEN)
    assert not set(names) & set(dataset.db.columns)


def test_signal_feature_matrix_has_no_metadata(dataset, config):
    path = Path(config["data"]["features_path"])
    if not path.exists():
        pytest.skip("feature table not built")
    feats = pd.read_csv(path, index_col="ecg_id", nrows=200)
    assert list(feats.columns) == all_columns()
    meta = dataset.db.loc[feats.index]
    X = feature_matrix(feats, meta, "signal")
    assert list(X.columns) == feature_names()
    assert not set(X.columns) & (set(FORBIDDEN) | set(dataset.db.columns))


def test_age_sex_only_in_ablation(dataset, config):
    path = Path(config["data"]["features_path"])
    if not path.exists():
        pytest.skip("feature table not built")
    feats = pd.read_csv(path, index_col="ecg_id", nrows=50)
    X = feature_matrix(feats, dataset.db.loc[feats.index], "signal+age_sex")
    assert set(X.columns) - set(feature_names()) == {"age", "sex"}


def test_feature_extraction_reads_only_waveform_files():
    src = Path(feature_extraction.__file__).read_text(encoding="utf-8")
    quoted = set(re.findall(r"[\"']([A-Za-z_0-9]+)[\"']", src))
    used_metadata = quoted & set(FORBIDDEN)
    # filename_hr: path to the 500 Hz file; ecg_id: row index of the output table (not a feature)
    assert used_metadata <= {"filename_hr", "ecg_id"}, used_metadata
    assert "ptbxl_database" not in src and "scp_statements" not in src
